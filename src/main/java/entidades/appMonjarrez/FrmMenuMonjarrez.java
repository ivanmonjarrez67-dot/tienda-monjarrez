    private static boolean esClaveValida(String clave) {

        int[] digitos = new int[4];
        for (int i = 0; i < 4; i++) { // 0-3
            digitos[i] = Character.getNumericValue(clave.charAt(i));

            if (digitos[i] < 0 || digitos[i] > 9) {
                return false;
            }
        }

        /**
         * cada dígito sea el doble del anterior
         * se toma el dijito anterior i-1 % digito de unidades
         * Verificamos que la clave tenga 4 dígitos
         */

        int claveEsperada;
        for (int i = 1; i < 4; i++) {
            claveEsperada = (digitos[i - 1] * 2) % 10;
            if (digitos[i] != claveEsperada) {
                return false;
            }
        }

        if (clave.length() != 4) {
            return false;
        }

        return true;

    }

