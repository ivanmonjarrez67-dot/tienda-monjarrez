    private void btnAdministradorActionPerformed(java.awt.event.ActionEvent evt) {

        String clave;
        int intentos = 0;
        boolean claveValida = false;

        while (intentos < 3 && !claveValida) {

            clave = JOptionPane.showInputDialog(" Señor usuario ingrese su clave:");

            if (clave == null || clave.isEmpty()) {

                JOptionPane.showMessageDialog(null, "Programa cerrado.");
                return;
            }

            if (esClaveValida(clave)) {
                JOptionPane.showMessageDialog(null, "ingresando..... " + clave);
                claveValida = true;

                MDI_MenuMonjarrez oMDI_MenuMonjarrez = new MDI_MenuMonjarrez();

                oMDI_MenuMonjarrez.setExtendedState(JFrame.MAXIMIZED_BOTH);

                oMDI_MenuMonjarrez.setVisible(true);

            } else {
                JOptionPane.showMessageDialog(null, "Clave inválida. Intente nuevamente.");
                intentos++;
            }
        }

        if (!claveValida) {
            JOptionPane.showMessageDialog(null, "Lo sentimos se han agotado los intentos, El programa se cerrará.");
        }

    }

