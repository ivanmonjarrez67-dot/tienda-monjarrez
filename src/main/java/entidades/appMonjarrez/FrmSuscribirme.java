    /**
     * Método para validar el número de tarjeta
     */
    private boolean validarNumeroTarjeta(String numeroTarjeta) {
        if (numeroTarjeta == null || !numeroTarjeta.matches("\\d+")) {
            return false;
        }

        int longitud = numeroTarjeta.length();
        String primerDigito = numeroTarjeta.substring(0, 1);
        String rangoMasterCard = numeroTarjeta.substring(0, 2);

        if (longitud == 16 && (primerDigito.equals("4")
                || (Integer.parseInt(rangoMasterCard) >= 51 && Integer.parseInt(rangoMasterCard) <= 55))) {
            return true;
        } else if (longitud == 15 && (primerDigito.equals("3"))) {
            return true;
        } else if (longitud == 16 && primerDigito.equals("6")) {
            return true;
        }
        return false;
    }

    /**
     * Método para validar el código de seguridad
     */
    private boolean validarCodigoSeguridad(String numeroTarjeta, String codigoSeguridad) {
        if (codigoSeguridad == null || !codigoSeguridad.matches("\\d+")) {
            return false;
        }

        int longitud = codigoSeguridad.length();
        if (numeroTarjeta.length() == 16) {
            return longitud == 3;
        } else if (numeroTarjeta.length() == 15) {
            return longitud == 4;
        }
        return false;
    }

