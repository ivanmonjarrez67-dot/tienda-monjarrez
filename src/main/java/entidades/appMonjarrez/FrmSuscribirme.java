    /**
     * @param evt
     */
    private void btnSuscribirmeActionPerformed(java.awt.event.ActionEvent evt) {
    // Verificar si se ha seleccionado un tipo de suscripción
    if (!rbNormal.isSelected() && !rbAvanzada.isSelected()) {
        JOptionPane.showMessageDialog(this, "Por favor, seleccione un tipo de suscripción (Básica o Avanzada).");
        return;
    }

    // Determinar el tipo de suscripción
    String tipoSuscripcion = rbNormal.isSelected() ? "Básica" : "Avanzada";
    Suscripcion suscripcion = new Suscripcion(tipoSuscripcion);

    JOptionPane.showMessageDialog(this, "Tipo de suscripción: " + suscripcion.getTipo() +
            "\nCosto: " + suscripcion.getCosto() +
            "\nBeneficios: " + suscripcion.getBeneficios());

    // Solicitar método de pago
    String metodoPagoStr = JOptionPane.showInputDialog(this, "¿Cómo desea pagar? (efectivo/tarjeta):");
    ETipoPago metodoPago;

    if (metodoPagoStr == null
            || (!metodoPagoStr.equalsIgnoreCase("efectivo") && !metodoPagoStr.equalsIgnoreCase("tarjeta"))) {
        JOptionPane.showMessageDialog(this, "Método de pago inválido.");
        return;
    } else if (metodoPagoStr.equalsIgnoreCase("efectivo")) {
        metodoPago = ETipoPago.EFECTIVO;
    } else {
        metodoPago = ETipoPago.TARJETA;

        String numeroTarjeta = JOptionPane.showInputDialog(this, "Ingrese el número de tarjeta (Sin espacios):");
        if (!validarNumeroTarjeta(numeroTarjeta)) {
            JOptionPane.showMessageDialog(this, "Número de tarjeta inválido.");
            return;
        }

        String codigoSeguridad = JOptionPane.showInputDialog(this, "Ingrese el código de seguridad:");
        if (!validarCodigoSeguridad(numeroTarjeta, codigoSeguridad)) {
            JOptionPane.showMessageDialog(this, "Código de seguridad inválido.");
            return;
        }

        String montoTarjetaStr = JOptionPane.showInputDialog(this, "Ingrese el monto a pagar con tarjeta:");
        if (montoTarjetaStr == null || !montoTarjetaStr.matches("\\d+(\\.\\d{1,2})?")) {
            JOptionPane.showMessageDialog(this, "Monto inválido.");
            return;
        }

        double montoTarjeta = Double.parseDouble(montoTarjetaStr);
        if (montoTarjeta < suscripcion.getCosto()) {
            JOptionPane.showMessageDialog(this, "El monto ingresado es menor que el precio a pagar.");
            return;
        }
    }

    // Procesar el pago en efectivo
    if (metodoPago == ETipoPago.EFECTIVO) {
        double descuento = suscripcion.getCosto() * 0.10;
        double montoConDescuento = suscripcion.getCosto() - descuento;

        String montoEfectivoStr = JOptionPane.showInputDialog(this, "Ingrese el monto con el que cancela:");
        if (montoEfectivoStr == null || !montoEfectivoStr.matches("\\d+(\\.\\d{1,2})?")) {
            JOptionPane.showMessageDialog(this, "Monto inválido.");
            return;
        }

        double montoEfectivo = Double.parseDouble(montoEfectivoStr);
        if (montoEfectivo < montoConDescuento) {
            JOptionPane.showMessageDialog(this, "El monto ingresado es menor que el total a pagar con descuento.");
            return;
        }

        double vuelto = montoEfectivo - montoConDescuento;
        JOptionPane.showMessageDialog(this, "El vuelto a entregar es: " + vuelto);
    }

// Validar correo y contraseña
try {
    if (txtCorreo.getText().isEmpty() || txtContraseña.getPassword().length == 0) {
        JOptionPane.showMessageDialog(this,
                "Estimado Usuario. Debe digitar sus datos de Inicio para acceder a su cuenta");
        return;
    }

    String correo = txtCorreo.getText();
    String contraseña = new String(txtContraseña.getPassword()); // Convertir char[] a String
    String hashedPassword = hashContraseña(contraseña); // Hashear la contraseña ingresada
    String cedula = txtCedula.getText();
    String ubicacion = txtUbicación.getText();

    // Conectar a la base de datos
    try (Connection conn = DatabaseConnection.getConnection()) {
        String sql = "SELECT * FROM Usuarios WHERE correo = ? AND contraseña = ?";
        try (PreparedStatement pstmt = conn.prepareStatement(sql)) {
            pstmt.setString(1, correo);
            pstmt.setString(2, hashedPassword); // Comparar el hash

            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Inicio de sesión exitosa");
                    JOptionPane.showMessageDialog(this, "Bienvenido!!");

                    // Registrar al vendedor usando el correo
                    vRegistro.registrarVendedor(cedula, ubicacion, 1, tipoSuscripcion, correo);
                    JOptionPane.showMessageDialog(null, "Bienvenido Emprendedor !!");

                    FrmEmpresa oFrmEmpresa = new FrmEmpresa();
                    oFrmEmpresa.setExtendedState(JFrame.MAXIMIZED_BOTH);
                    oFrmEmpresa.setVisible(true);

                    intentos = 0;
                    this.dispose();
                } else {
                    // Si no se encuentra el usuario
                    JOptionPane.showMessageDialog(this, "Credenciales incorrectas. Intente nuevamente.");
                    txtCorreo.setText("");
                    txtContraseña.setText("");

                    intentos++;
                    if (intentos >= 3) {
                        JOptionPane.showMessageDialog(null,
                                "Lo sentimos, se han agotado los intentos. El programa se cerrará.");
                        this.dispose();
                    }
                }
            }
        }
    }
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Ocurrió un error durante el inicio de sesión: " + e.getMessage());
    e.printStackTrace();
}



    this.dispose();
}



    // Método simulado para "hash" de la contraseña
    private String hashContraseña(String contraseña) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(contraseña.getBytes(StandardCharsets.UTF_8));
            StringBuilder hexString = new StringBuilder();
            for (byte b : hash) {
                String hex = Integer.toHexString(0xff & b);
                if (hex.length() == 1)
                    hexString.append('0');
                hexString.append(hex);
            }
            return hexString.toString();
        } catch (NoSuchAlgorithmException e) {
            throw new RuntimeException(e);
        }
    }

