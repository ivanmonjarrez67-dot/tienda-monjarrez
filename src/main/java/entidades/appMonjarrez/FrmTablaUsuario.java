    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            if (tblUsuario.getSelectedRow() >= 0) {

                int id = (int) modeloTabla.getValueAt(tblUsuario.getSelectedRow(), 0);

                oUsuario = PersistenciaUsuarioTabla.getUsuario(id);

                if (oUsuario != null) {

                    FrmRegistrarVendedor oFrmRegistrarUsuario = new FrmRegistrarVendedor(TipoMantenimiento.MODIFICAR,
                            oUsuario);
                    oFrmRegistrarUsuario.setAlwaysOnTop(true);
                    oFrmRegistrarUsuario.setVisible(true);

                    oFrmRegistrarUsuario.addWindowListener(new WindowAdapter() {
                        @Override
                        public void windowClosed(WindowEvent e) {
                            llenarTabla();
                        }
                    });
                } else {
                    JOptionPane.showMessageDialog(this, "Error: No se encontró el usuario.");
                }
            } else {
                JOptionPane.showMessageDialog(this, "Debe seleccionar un usuario para modificar.");
            }
        } catch (ClassCastException e) {
            JOptionPane.showMessageDialog(this, "Error al obtener el ID del usuario: " + e.getMessage());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage());
        }
    }

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            int respuesta = JOptionPane.showConfirmDialog(this, "¿Está seguro de que desea eliminar este usuario?",
                    "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
            if (respuesta == JOptionPane.YES_OPTION) {
                if (tblUsuario.getSelectedRow() >= 0) {

                    int id = (int) modeloTabla.getValueAt(tblUsuario.getSelectedRow(), 0);

                    PersistenciaUsuarioTabla.eliminarUsuario(id);

                    llenarTabla();

                } else {
                    JOptionPane.showMessageDialog(this, "Debe seleccionar un usuario para eliminar.");
                }
            }
        } catch (ClassCastException e) {
            JOptionPane.showMessageDialog(this, "Error al obtener el ID del usuario: " + e.getMessage());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage());
        }

    }

