    private void llenarTablaSolicitudes() {
        modeloSolicitudes.setRowCount(0);

        List<SolicitudesDeVendedor> solicitudes = PersistenciaSolicitudUsuario.obtenerSolicitudes();
        System.out.println("Número de solicitudes: " + solicitudes.size());

        for (SolicitudesDeVendedor solicitud : solicitudes) {
            Object[] fila = new Object[1];

            fila[0] = "ID: " + solicitud.getId() + ", Provincia: " + solicitud.getProvincia() +
                    ", Cantón: " + solicitud.getCanton() + ", Producto: " + solicitud.getNombreProducto() +
                    ", Descripción: " + solicitud.getDescripcion() +
                    ", Precio Promedio: " + solicitud.getPrecioPromedio() +
                    ", Correo: " + solicitud.getCorreoVendedor();
            modeloSolicitudes.addRow(fila);
        }

    }

    private void llenarTabla() {
        modeloTabla.setRowCount(0);
        List<Usuario> usuarios = PersistenciaUsuarioTabla.getListado();
        System.out.println("Número de usuarios: " + usuarios.size());
        for (Usuario usuario : usuarios) {
            Object[] fila = new Object[6];
            fila[0] = usuario.getId();
            fila[1] = usuario.getNombre();
            fila[2] = usuario.getCorreo();
            fila[3] = usuario.getContraseña();
            fila[4] = usuario.getTipo();
            fila[5] = usuario.getCedula();

            modeloTabla.addRow(fila);
        }

    }

